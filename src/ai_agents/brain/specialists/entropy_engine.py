def roll_identity(theme_override: str = None) -> dict:
    """
    Бросает кубик и собирает уникальную личность (энтропию) для ИИ.
    """
    persona = random.choice(PERSONAS)
    quirk1 = random.choice(QUIRKS)
    
    # Берем другой quirk, чтобы не совпадал с первым (если повезет)
    quirk2 = random.choice(QUIRKS)
    while quirk2 == quirk1:
        quirk2 = random.choice(QUIRKS)
        
    # Выбираем случайные 3 жестких ограничения
    random_constraints = random.sample(CONSTRAINTS, k=min(3, len(CONSTRAINTS)))
    
    return {
        "persona": persona,
        "quirks": [quirk1, quirk2],
        "constraints": random_constraints
    }
